/* BS 2000-01-01 = AD 1943-04-14 */
var BS_EPOCH_AD = { y: 1943, m: 4, d: 14 };

var NEPALI_DIGITS = ['०', '१', '२', '३', '४', '५', '६', '७', '८', '९'];

function toNepaliDigits(numStr) {
    var s = String(numStr);
    var out = '';
    for (var i = 0; i < s.length; i++) {
        var c = s[i];
        out += (c >= '0' && c <= '9') ? NEPALI_DIGITS[Number(c)] : c;
    }
    return out;
}

function bsYearTotal(y) {
    var arr = BS_MONTH_DAYS[y];
    if (!arr) return 0;
    var t = 0;
    for (var i = 0; i < 12; i++) t += arr[i];
    return t;
}

/* BS -> AD: returns JS Date or null if invalid/out of range */
function bsToAd(bsY, bsM, bsD) {
    if (!BS_MONTH_DAYS[bsY]) return null;
    var daysInMonth = BS_MONTH_DAYS[bsY][bsM - 1];
    if (!daysInMonth || bsM < 1 || bsM > 12 || bsD < 1 || bsD > daysInMonth) return null;

    var total = 0;
    for (var y = 2000; y < bsY; y++) total += bsYearTotal(y);
    for (var m = 0; m < bsM - 1; m++) total += BS_MONTH_DAYS[bsY][m];
    total += bsD - 1;

    var ad = new Date(BS_EPOCH_AD.y, BS_EPOCH_AD.m - 1, BS_EPOCH_AD.d);
    ad.setDate(ad.getDate() + total);
    return ad;
}

/* AD -> BS: returns {y, m, d} or null if out of range */
function adToBs(adY, adM, adD) {
    var epoch = new Date(BS_EPOCH_AD.y, BS_EPOCH_AD.m - 1, BS_EPOCH_AD.d);
    var target = new Date(adY, adM - 1, adD);
    if (isNaN(target.getTime())) return null;
    var diff = Math.round((target - epoch) / 86400000);
    if (diff < 0) return null;

    var y = 2000;
    while (BS_MONTH_DAYS[y] && diff >= bsYearTotal(y)) {
        diff -= bsYearTotal(y);
        y++;
    }
    if (!BS_MONTH_DAYS[y]) return null;

    var m = 1;
    while (m <= 12 && diff >= BS_MONTH_DAYS[y][m - 1]) {
        diff -= BS_MONTH_DAYS[y][m - 1];
        m++;
    }
    if (m > 12) return null;
    return { y: y, m: m, d: diff + 1 };
}
